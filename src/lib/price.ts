/** 一樣材料大約多少錢；不知道價錢（自己加的材料）回傳 null */
export function lineCost(name: string, q: number, unit: string): number | null {
  if (unit === 'g' || unit === '克') return name in PER_100G ? (PER_100G[name] * q) / 100 : null
  const p = EACH[`${name}|${unit}`] ?? EACH[name]
  return p === undefined ? null : p * q
}

/** 這餐材料大約多少錢（四捨五入到 10 元），和沒有價錢的材料 */
export function mealCost(food: Pick<FoodLine, 'name' | 'q' | 'unit'>[]) {
  let sum = 0
  const unknown: string[] = []
  for (const f of food) {
    const c = lineCost(f.name, f.q, f.unit)
    if (c === null) unknown.push(f.name)
    else sum += c
  }
  return { total: Math.round(sum / 10) * 10, unknown }
}

/** 畫面上的一句話，例如「約 $320」；全部都沒價錢就回空字串 */
export function costText(food: Pick<FoodLine, 'name' | 'q' | 'unit'>[]) {
  const { total, unknown } = mealCost(food)
  if (!total) return ''
  return `約 $${total.toLocaleString('en-US')}${unknown.length ? `（${unknown.length} 樣沒算）` : ''}`
}
