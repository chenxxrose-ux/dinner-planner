export function parseIng(s: string): [string, number, string][] {
  if (!s) return []
  return s.split(',').map((x) => {
    const m = x.trim().match(/^(.+?) ([\d.]+)(.+)$/)
    if (!m) throw new Error(`食材格式不對：${x}`)
    return [m[1], parseFloat(m[2]), m[3]]
  })
}

export function parseSauce(s: string): [string, string][] {
  if (!s) return []
  return s.split(',').map((x) => {
    const t = x.trim()
    const i = t.indexOf(' ')
    return [t.slice(0, i), t.slice(i + 1)]
  })
}

